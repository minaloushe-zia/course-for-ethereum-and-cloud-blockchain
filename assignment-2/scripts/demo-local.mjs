import fs from 'node:fs';
import { JsonRpcProvider, Contract, keccak256, toUtf8Bytes } from 'ethers';
const provider = new JsonRpcProvider('http://127.0.0.1:8545', undefined, { cacheTimeout: -1 });
provider.pollingInterval = 100;
if ((await provider.getNetwork()).chainId !== 31337n) throw new Error('Local chain only');
const data = JSON.parse(fs.readFileSync(new URL('../deployments/local.json', import.meta.url)));
const abi = name => JSON.parse(fs.readFileSync(new URL('../artifacts/' + name + '.json', import.meta.url))).abi;
const casino = new Contract(data.casinoAddress, abi('Casino'), provider);
if (await casino.numberOfBets() !== 0n || await casino.awaitingRandomness()) throw new Error('Use a fresh round');
const round = await casino.currentRoundId();
const min = await casino.minimumBet();
for (let i = 0; i < 100; i++) await (await casino.connect(await provider.getSigner(i)).bet(i % 10 + 1, { value: min })).wait();
const result = 'clearly-labeled-local-result';
const winningNumber = Number(BigInt(keccak256(toUtf8Bytes(result))) % 10n) + 1;
const oracle = new Contract(data.oracleAddress, abi('LocalOracle'), await provider.getSigner(0));
await (await oracle.fulfill(await casino.pendingQueryId(), result)).wait();
const winner = await provider.getSigner(winningNumber - 1);
await (await casino.connect(winner).claimPrize(round, await winner.getAddress())).wait();
console.log(`LOCAL SIMULATION: 100 distinct bets; automatic Oraclize-format request; winning number ${winningNumber}; prize collected; next round opened. Ledger proof is NOT tested by this harness.`);
await provider.destroy();
